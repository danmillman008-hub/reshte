def load_choice_csv():
    """Read the committed 150-choice CSV so a PDF rebuild does not depend on /tmp."""
    with OUTPUT_CSV.open(encoding='utf-8', newline='') as f:
        rows = list(csv.DictReader(f))
    choices = [
        (r['کدرشته‌محل'], r['رشته'], r['دانشگاه'], r['دوره'], r['شروع'], r['شرط/یادداشت'])
        for r in rows
    ]
    assert len(choices) == 150 and len({r[0] for r in choices}) == 150
    return choices


