# ReportLab does not perform Arabic shaping / bidirectional text layout itself.
def rtl(text: object) -> str:
    s = str(text).replace('\n', '<br/>')
    # Preserve ReportLab's simple markup while shaping plain runs.
    if '<' in s:
        parts = []
        buffer = ''
        for ch in s:
            if ch == '<':
                if buffer:
                    parts.append(get_display(reshape(buffer)))
                    buffer = ''
                parts.append(ch)
            elif ch == '>':
                parts.append(ch)
            else:
                buffer += ch
        if buffer:
            parts.append(get_display(reshape(buffer)))
        return ''.join(parts)
    return get_display(reshape(s))


def p(text, style):
    return Paragraph(rtl(text), style)


