def write_choice_csv(choices):
    with OUTPUT_CSV.open('w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['اولویت', 'کدرشته‌محل', 'رشته', 'دانشگاه', 'دوره', 'شروع', 'شرط/یادداشت'])
        for idx, row in enumerate(choices, 1):
            writer.writerow([idx, *row])


